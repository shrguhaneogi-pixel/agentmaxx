/**
 * THE AGENT
 *
 * An agent is a loop:
 *   1. Send the chat + the list of tools to Gemini.
 *   2. If Gemini wants to call a tool -> run it, send back the result, repeat.
 *   3. If Gemini answers with text -> done.
 */
import { GoogleGenAI, type Content, type Part } from "@google/genai";
import { tools } from "./tools";

export const MODEL = process.env.GEMINI_MODEL || "gemini-flash-latest";
const MAX_STEPS = 5;

const SYSTEM_PROMPT =
  "You are a helpful agent with your own crypto wallet. Use your tools when they help. " + 
  "You are a travel agent. When the user asks about a destination, use the country info tool to get information about the capital and population. Suggest a popular local cuisine to the user." +
  "If a tool costs money, just use it: your wallet pays automatically. Keep answers short and to the point.";

export type ChatMessage = { role: "user" | "agent"; text: string };
export type Step = { tool: string; args: unknown; result: unknown; error?: boolean };
export type AgentRunResult = { answer: string; steps: Step[] };

export async function runAgent(
  history: ChatMessage[],
  ctx: { baseUrl: string }
): Promise<AgentRunResult> {
  const ai = new GoogleGenAI({ apiKey: process.env.GEMINI_API_KEY });
  const contents: Content[] = history.map((m) => ({
    role: m.role === "user" ? "user" : "model",
    parts: [{ text: m.text }],
  }));
  const steps: Step[] = [];

  for (let i = 0; i < MAX_STEPS; i++) {
    let response;
    const generateConfig = {
      systemInstruction: SYSTEM_PROMPT,
      tools: [
        {
          functionDeclarations: tools.map((t) => ({
            name: t.name,
            description: t.description,
            parametersJsonSchema: t.parameters,
          })),
        },
      ],
    };

    try {
      response = await ai.models.generateContent({
        model: MODEL,
        contents,
        config: generateConfig,
      });
    } catch (err: unknown) {
      const errStr = String(err);
      if (errStr.includes("503") || errStr.includes("UNAVAILABLE") || errStr.includes("429")) {
        await new Promise((resolve) => setTimeout(resolve, 1500));
        response = await ai.models.generateContent({
          model: MODEL,
          contents,
          config: generateConfig,
        });
      } else {
        throw err;
      }
    }

    const calls = response.functionCalls ?? [];
    if (calls.length === 0) {
      const parts = response.candidates?.[0]?.content?.parts;
      const joinedParts = parts
        ?.map((p: Part) => p.text)
        .filter((t): t is string => Boolean(t))
        .join("\n");

      const answer = response.text || joinedParts || "I completed your request.";
      return { answer, steps };
    }

    // Keep Gemini's turn in the history, then run every tool it asked for.
    const candidateContent = response.candidates?.[0]?.content;
    if (!candidateContent) {
      return { answer: response.text || "No response content generated by model.", steps };
    }
    contents.push(candidateContent);
    const results: Part[] = [];

    for (const call of calls) {
      const toolName = call.name || "unknown_tool";
      const tool = tools.find((t) => t.name === toolName);
      let result: unknown;
      let error = false;
      const toolArgs = (call.args && typeof call.args === "object" ? call.args : {}) as Record<string, unknown>;
      try {
        if (!tool) throw new Error(`No tool named ${toolName}`);
        result = await tool.run(toolArgs, ctx);
      } catch (err: unknown) {
        result = { error: err instanceof Error ? err.message : String(err) };
        error = true;
      }
      steps.push({ tool: toolName, args: toolArgs, result, error });
      results.push({ functionResponse: { id: call.id, name: toolName, response: { result } } });
    }

    contents.push({ role: "user", parts: results });
  }

  return { answer: "I hit my step limit. Try a simpler question.", steps };
}

